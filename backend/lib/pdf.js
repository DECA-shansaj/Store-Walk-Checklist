/**
 * Generate a simple PDF buffer from checklist report text.
 * Uses pdfkit (declared in package.json). No API keys required.
 */
const PDFDocument = require("pdfkit");

function buildPdfBuffer(record) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 50, size: "LETTER" });
      const chunks = [];
      doc.on("data", (c) => chunks.push(c));
      doc.on("end", () => resolve(Buffer.concat(chunks)));
      doc.on("error", reject);

      doc.fontSize(16).text("Gulfport Store Walk Checklist", { underline: true });
      doc.moveDown(0.5);
      doc.fontSize(10);
      doc.text("Record ID: " + (record.id || ""));
      doc.text("Central ID: " + (record.centralId || ""));
      doc.text("Role: " + (record.role || record.type || ""));
      doc.text("Manager: " + (record.managerName || ""));
      doc.text("Date: " + (record.dateDisplay || record.dateISO || ""));
      doc.text("Start: " + (record.startTime || ""));
      doc.text("End: " + (record.endTime || ""));
      doc.text("Submitted: " + (record.submittedAt || ""));
      doc.text("Open issues: " + (record.openIssuesAtCompletion || 0));
      doc.moveDown();
      doc.fontSize(9).text(record.reportText || "(no report text)", {
        align: "left",
      });
      doc.moveDown();
      doc.fontSize(8).fillColor("#666").text(
        "Generated by Gulfport Store Walk API. Do not include CUI or unnecessary personal data in remarks."
      );
      doc.end();
    } catch (e) {
      reject(e);
    }
  });
}

module.exports = { buildPdfBuffer };
